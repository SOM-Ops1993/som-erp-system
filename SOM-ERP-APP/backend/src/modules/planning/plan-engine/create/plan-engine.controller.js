import prisma from '../../../../db.js'

const nextPlanId = async () => {
  const year = new Date().getFullYear()
  const seq = await prisma.planSequence.upsert({ where: { year }, create: { year, seq: 1 }, update: { seq: { increment: 1 } } })
  return `PP-${year}-${String(seq.seq).padStart(4, '0')}`
}

const checkRmAvailability = async (productCode, batchQtyKg) => {
  const recipe = await prisma.recipeDb.findMany({ where: { productCode } })
  if (!recipe.length) return { status: 'AMBER', details: [], note: 'No BOM found' }
  const details = []
  let worstStatus = 'GREEN'
  for (const row of recipe) {
    const required = row.qtyPerUnit * batchQtyKg
    const ledgerRows = await prisma.stockLedger.findMany({ where: { itemCode: row.rmCode }, orderBy: { timestamp: 'desc' }, take: 1 })
    const available = ledgerRows[0]?.balance ?? 0
    let status = 'GREEN'
    if (available <= 0)            { status = 'RED';   worstStatus = 'RED' }
    else if (available < required) { status = 'AMBER'; if (worstStatus !== 'RED') worstStatus = 'AMBER' }
    details.push({ rmCode: row.rmCode, rmName: row.rmName, required: +required.toFixed(3), available: +available.toFixed(3), uom: row.uom, roleType: row.roleType, status })
  }
  return { status: worstStatus, details }
}

export const runPlanningEngine = async (trigger = 'MANUAL') => {
  const today = new Date()
  const PRIORITY_ORDER = { VERY_URGENT: 0, URGENT: 1, MODERATE: 2 }
  const pendingItems = await prisma.salesOrderItem.findMany({
    where: { status: 'PENDING' },
    include: { salesOrder: { select: { id: true, diNo: true, customerName: true, priority: true, estimatedDispatchDate: true, company: true } } }
  })
  pendingItems.sort((a, b) => {
    const pa = PRIORITY_ORDER[a.salesOrder.priority] ?? 2
    const pb = PRIORITY_ORDER[b.salesOrder.priority] ?? 2
    if (pa !== pb) return pa - pb
    return new Date(a.salesOrder.estimatedDispatchDate) - new Date(b.salesOrder.estimatedDispatchDate)
  })
  let plansCreated = 0
  const errors = []
  for (const item of pendingItems) {
    try {
      const existing = await prisma.productionPlan.findFirst({ where: { salesOrderItemId: item.id, status: { notIn: ['CANCELLED'] } } })
      if (existing) continue
      const so = item.salesOrder
      const etd = new Date(so.estimatedDispatchDate)
      const planTarget = new Date(etd)
      planTarget.setDate(planTarget.getDate() - 3)
      const tomorrow = new Date(today)
      tomorrow.setDate(tomorrow.getDate() + 1)
      const plannedDate = planTarget > tomorrow ? planTarget : tomorrow
      let productCode = item.inhouseProductCode || null
      if (!productCode && item.inhouseProductName) {
        const pm = await prisma.productMaster.findFirst({ where: { productName: { equals: item.inhouseProductName, mode: 'insensitive' } }, select: { productCode: true } })
        if (pm) productCode = pm.productCode
      }
      const rmCheck = productCode ? await checkRmAvailability(productCode, item.totalQty) : { status: 'AMBER', details: [], note: 'No product code linked' }
      const planId = await nextPlanId()
      await prisma.$transaction(async (tx) => {
        await tx.productionPlan.create({
          data: { planId, salesOrderId: so.id, salesOrderItemId: item.id, diNo: so.diNo, customerName: so.customerName, sectionType: item.sectionName || 'POWDER', plannedDate, productCode, productName: item.inhouseProductName, totalQty: item.totalQty, uom: item.totalUom || 'KG', carrier: item.carrier || null, specs: item.activeSpecs || null, unitPackQty: item.unitQty || null, noOfUnits: item.totalCS || null, labels: item.labelType || null, rmCheckStatus: rmCheck.status, eqpCheckStatus: 'UNKNOWN', rmCheckDetails: rmCheck.details, autoGenerated: trigger === 'SCHEDULED', status: 'DRAFT' }
        })
        await tx.salesOrderItem.update({ where: { id: item.id }, data: { status: 'PLANNED' } })
      })
      plansCreated++
    } catch (err) {
      errors.push(`Item ${item.id}: ${err.message}`)
    }
  }
  await prisma.plannerLog.create({ data: { trigger, plansCreated, ordersProcessed: pendingItems.length, errors: errors.length ? errors.join(' | ') : null } })
  return { plansCreated, ordersProcessed: pendingItems.length, errors }
}

export const runEngine = async (req, res) => {
  try {
    const result = await runPlanningEngine('MANUAL')
    return res.json({ success: true, ...result })
  } catch (err) {
    return res.status(500).json({ success: false, error: err.message, code: 'INTERNAL_ERROR' })
  }
}
